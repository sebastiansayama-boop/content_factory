def format_text_variation_matrix() -> str:
    lines = [
        "TEXT VARIATION MATRIX: model must choose the writing mode from the evidence, not repeat a fixed template.",
        "Choose exactly one mode. Choose based on the strongest factual shape of the material.",
    ]
    for item in TEXT_VARIATION_MATRIX:
        lines.extend([
            f"- {item.id} ({item.name})",
            f"  When: {item.when}",
            f"  Opening: {item.opening}",
            f"  Movement: {item.movement}",
            f"  Rhythm: {item.rhythm}",
            f"  Ending: {item.ending}",
            f"  Avoid: {item.avoid}",
        ])
    return "\n".join(lines)
